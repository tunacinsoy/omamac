#!/opt/homebrew/bin/bash
# Everything after the restart: omamac's zsh file, the two guarded lines, a summary.
# shellcheck source-path=SCRIPTDIR
set -Eeuo pipefail

# Keep this check first and bash 3.2-safe: a Mac's /bin/bash must reach the message.
if [ "${BASH_VERSINFO[0]}" -lt 5 ]; then
  echo "omamac needs bash 5. Run the one-liner again; it installs bash for you." >&2
  exit 1
fi

OMAMAC_CHECKOUT=$(cd "$(dirname "$0")" && pwd -P)
# shellcheck source=lib/paths.sh
source "$OMAMAC_CHECKOUT/lib/paths.sh"
# shellcheck source=lib/lines.sh
source "$OMAMAC_CHECKOUT/lib/lines.sh"
# shellcheck source=lib/ui.sh
source "$OMAMAC_CHECKOUT/lib/ui.sh"

OMAMAC_STEP='starting'

install_failed() {
  ui_fail "omamac stopped while $OMAMAC_STEP. Log: $OMAMAC_LOG"
  ui_fail "Fix the problem and run the one-liner again; it picks up where it stopped."
  exit 1
}
trap install_failed ERR

# The file's text is exactly what the spec says; the quotes keep $PATH and $HOME literal.
install_zsh_file() {
  OMAMAC_STEP="writing $OMAMAC_ZSH_FILE"
  ui_step "omamac's zsh file"
  mkdir -p "$OMAMAC_CONFIG_DIR"
  local tmp
  tmp=$(mktemp "$OMAMAC_CONFIG_DIR/zshrc.XXXXXX")
  cat > "$tmp" <<'ZSH'
# Generated by omamac. Changes here are overwritten; put your own in ~/.zshrc.
[[ ":$PATH:" == *":$HOME/.local/share/omamac/bin:"* ]] || export PATH="$HOME/.local/share/omamac/bin:$PATH"
ZSH
  # Move into place only if different, so a second run leaves the file (and its mtime) alone.
  if cmp -s "$tmp" "$OMAMAC_ZSH_FILE"; then
    rm -f "$tmp"
  else
    mv "$tmp" "$OMAMAC_ZSH_FILE"
  fi
  ui_ok "omamac's zsh file is in place"
}

install_lines() {
  OMAMAC_STEP='adding Homebrew to ~/.zprofile'
  lines_add "$HOME/.zprofile" "$OMAMAC_ZPROFILE_LINE" 'brew shellenv'
  ui_ok "Homebrew is on the PATH"
  OMAMAC_STEP='adding omamac to ~/.zshrc'
  lines_add "$HOME/.zshrc" "$OMAMAC_ZSHRC_LINE"
  ui_ok "omamac is loaded by zsh"
}

install_summary() {
  OMAMAC_STEP='printing the summary'
  ui_box "Installed: Homebrew, bash, gum, omamac" "Log: $OMAMAC_LOG" "Open a new terminal window, then run omamac."
}

install_main() {
  install_zsh_file
  install_lines
  install_summary
}

install_main
